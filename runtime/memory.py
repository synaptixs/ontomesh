    def _row_to_jsonld(self, row: sqlite3.Row) -> Dict[str, Any]:
        """Convert an ObservationRecord DB row to a typed JSON-LD object."""
        d = dict(row)
        obj: Dict[str, Any] = {
            "@type":            "ObservationRecord",
            "@id":               d.get("record_iri", ""),
            "entity_iri":        d.get("entity_iri", ""),
            "entity_type":       d.get("entity_type", ""),
            "record_type":       d.get("record_type", ""),
            "derivation_method": d.get("derivation_method", ""),
            "confidence_score":  d.get("confidence_score"),
            "value_text":        d.get("value_text", ""),
            "source_ref":        d.get("source_ref", ""),
            "prov_agent_iri":    d.get("prov_agent_iri", ""),
            "generatedAt":       d.get("generated_at", ""),
            "valid_from":        d.get("valid_from", ""),
        }
